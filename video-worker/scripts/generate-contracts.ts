import { format } from 'prettier';
import { z } from 'zod';
import { planSchema } from '../src/contracts/ifeng.js';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const refs = path.resolve('../claude-code-video-toolkit/.claude/skills/video-pipeline/references');
writeFileSync(
  path.join(refs, 'analysis-v2.schema.json'),
  JSON.stringify(z.toJSONSchema(planSchema), null, 2) + '\n',
);
const schema = JSON.parse(readFileSync(path.join(refs, 'task-v2.schema.json'), 'utf8'));
function type(s: any): string {
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((x: any) => JSON.stringify(x)).join(' | ');
  if (Array.isArray(s.type)) return s.type.map((t: string) => type({ ...s, type: t })).join(' | ');
  if (s.type === 'object')
    return (
      '{ ' +
      Object.entries(s.properties ?? {})
        .map(([k, v]) => JSON.stringify(k) + (s.required?.includes(k) ? '' : '?') + ': ' + type(v))
        .join('; ') +
      ' }'
    );
  if (s.type === 'array') return '(' + type(s.items) + ')[]';
  return (
    (
      {
        integer: 'number',
        number: 'number',
        boolean: 'boolean',
        null: 'null',
        string: 'string',
      } as any
    )[s.type] ?? 'unknown'
  );
}
writeFileSync(
  'src/contracts/internal.generated.ts',
  await format(
    '// Generated by scripts/generate-contracts.ts from toolkit task-v2.schema.json.\nexport type InternalTask = ' +
      type(schema) +
      ';\n',
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  ),
);
